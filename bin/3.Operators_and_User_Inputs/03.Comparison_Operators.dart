void main() {
  int a = 10;
  int b = 5;

  print(a > b);   // true
  print(a < b);   // false
  print(a >= b);  // true
  print(a <= b);  // false
  print(a == b);  // false
  print(a != b);  // true
}
// 🧠 ব্যাখ্যা:
// > → বড়
// < → ছোট
// == → সমান
// != → সমান না

