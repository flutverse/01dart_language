void main() {
  // This is a single line comment

  /*
    This is a multi-line comment
  */

  // Variables & Data Types
  String name = "Arif";
  int age = 22;
  double height = 5.8;
  bool isStudent = true;

  // var
  var city = "Rajshahi";

  // final & const
  final country = "Bangladesh";
  const pi = 3.14;

  // dynamic
  dynamic data = "Hello";
  data = 100;

  // Output
  print("Name: $name");
  print("Age: $age");
  print("Height: $height");
  print("Student: $isStudent");
  print("City: $city");
  print("Country: $country");
  print("PI: $pi");
  print("Data: $data");
}

// 🧠 কী কী ব্যবহার হলো:
// main() → program start
// print() → output
// // /* */ → comment
// variable → int, double, String, bool
// var, final, const, dynamic